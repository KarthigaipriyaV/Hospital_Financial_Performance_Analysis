/* 8.4 Demographic Breakdown for the Top 3 Reason Codes Only (High-Cost Encounters) */

SELECT
    E.REASONCODE,
    P.GENDER,
    P.RACE,
    P.ETHNICITY,
    COUNT(*) AS HIGH_COST_ENCOUNTERS,
    SUM(E.TOTAL_CLAIM_COST) AS TOTAL_COST
FROM ENCOUNTERS E
JOIN PATIENTS P
    ON E.PATIENT = P.Id
WHERE E.REASONCODE IN
(
    SELECT TOP 3 REASONCODE
    FROM ENCOUNTERS
    WHERE REASONCODE IS NOT NULL
    GROUP BY REASONCODE

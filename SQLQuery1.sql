/* 9.11 Final: Total Base Cost, Payer Coverage, and Gap by Procedure and Payer Name */

SELECT
    P.CODE,
    P.DESCRIPTION,
    PY.NAME AS PAYER_NAME,
    SUM(P.BASE_COST) AS TOTAL_BASE_COST,
    SUM(E.PAYER_COVERAGE) AS TOTAL_PAYER_COVERAGE,

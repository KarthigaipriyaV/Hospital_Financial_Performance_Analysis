/ *10. IDENTIFYING PATIENTS WITH MULTIPLE PROCEDURES
       ACROSS ENCOUNTERS  */

  /* 10.1 Patients with the Same Reason Code Across Multiple Encounters/Procedures */

SELECT
    P.PATIENT,
    P.REASONCODE,
    COUNT(DISTINCT P.ENCOUNTER) AS ENCOUNTERS_WITH_PROCEDURE,
    COUNT(*) AS TOTAL_PROCEDURES,
    SUM(P.BASE_COST) AS TOTAL_PROCEDURE_COST
FROM PROCEDURES P
WHERE P.REASONCODE IS NOT NULL
GROUP BY
    P.PATIENT,
    P.REASONCODE
HAVING COUNT(DISTINCT P.ENCOUNTER) > 1
ORDER BY TOTAL_PROCEDURE_COST DESC;

/ * 11 .Analyzing Patient Encounter Duration for Different Classes */

/* 11.1 Average Duration and Encounters Over 24 Hours, by Organization and Encounter Class */

SELECT 
    o.NAME AS Organization,
    e.ENCOUNTERCLASS AS Encounter_Class,
    COUNT(*) AS Total_Encounters,
    AVG(DATEDIFF(MINUTE, e.START, e.STOP)) / 60.0 AS Avg_Duration_Hours,
    SUM(CASE WHEN DATEDIFF(HOUR, e.START, e.STOP) > 24 THEN 1 ELSE 0 END) AS Encounters_Over_24hrs
FROM Encounters e
JOIN organizations3 o
    ON e.ORGANIZATION = o.Id
GROUP BY 
    o.NAME, 
    e.ENCOUNTERCLASS
ORDER BY 
    o.NAME, Avg_Duration_Hours DESC;

    
